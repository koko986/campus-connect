insert into public.universities (
  slug, name, short_name, university_type, city, region, country_code,
  founded_year, description, is_published, data_source_url
)
select
  slug,
  name,
  short_name,
  university_type::public.university_type,
  city,
  region,
  'MM',
  founded_year,
  description,
  true,
  'https://www.unirank.org/mm/a-z/'
from missing
on conflict (slug) do update set
  region = coalesce(public.universities.region, excluded.region),
  founded_year = coalesce(public.universities.founded_year, excluded.founded_year),
  data_source_url = excluded.data_source_url,
  is_published = true,
  archived_at = null,
  updated_at = now();

