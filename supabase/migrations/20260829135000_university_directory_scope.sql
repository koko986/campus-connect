-- uniRank's 2026 Myanmar directory, while preserving the existing real
-- University of Information Technology row whose official site confirms its
-- degree programmes. An earlier draft imported the broader Wikipedia list,
-- which also contains institutions outside the agreed scope.
--
-- This migration is intentionally separate from the canonical seed migration:
-- fresh databases get only the 96 rows from 20260829120000, while databases
-- that received the broader draft are brought back to the same state without
-- deleting rows that posts or profiles may reference.

