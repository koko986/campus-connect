insert into public.programs (university_id, department_id, name, degree_level, description, source_url)
select u.id, null, cp.name, cp.degree_level,
  'Degree or credential listed in the collected university catalog.',
  coalesce(u.website_url, u.data_source_url)
from collected_programs cp
join public.universities u on u.slug = cp.slug
where not exists (
  select 1 from public.programs p
  where p.university_id = u.id and lower(p.name) = lower(cp.name)
);

