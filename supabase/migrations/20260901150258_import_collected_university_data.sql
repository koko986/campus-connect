set
  founded_year = coalesce(u.founded_year, c.founded_year),
  website_url = coalesce(u.website_url, c.website_url),
  about = case
    when u.about is null or u.about = 'A quieter, greener campus experience with accessible lecturers.' then c.about
    else u.about
  end,
  data_source_url = case
    when c.website_url is not null
      and (u.data_source_url is null
        or u.data_source_url like 'https://www.unirank.org/%'
        or u.data_source_url like 'https://en.wikipedia.org/%')
      then c.website_url
    else u.data_source_url
  end,
  data_verified_at = '2026-09-01'::timestamptz,
  updated_at = now()
from collected c
where u.slug = c.slug;

